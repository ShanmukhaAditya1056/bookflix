"""Generate the idempotent Flyway seed migration from catalog.json.

Usage (from repo root):
    python bookflix-backend/database/seed/generate_seed_sql.py

Writes bookflix-backend/backend/src/main/resources/db/seed/R__seed_catalog.sql.
The output uses explicit ids + INSERT IGNORE, so re-running it never duplicates rows and never
overwrites edits an admin made to seeded rows. Users (including admins) are NOT seeded here.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CATALOG = HERE / "catalog.json"
OUTPUT = HERE.parent.parent / "backend" / "src" / "main" / "resources" / "db" / "seed" / "R__seed_catalog.sql"


def sql_str(value: str | None) -> str:
    if value is None:
        return "NULL"
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def sql_int(value: int | None) -> str:
    return "NULL" if value is None else str(int(value))


def main() -> int:
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    genres = data["genres"]
    authors = data["authors"]
    books = data["books"]
    slug_to_id = {g["slug"]: g["id"] for g in genres}
    author_ids = {a["id"] for a in authors}

    errors = []
    for b in books:
        if b["authorId"] not in author_ids:
            errors.append(f"book {b['id']} references unknown author {b['authorId']}")
        for slug in b["genres"]:
            if slug not in slug_to_id:
                errors.append(f"book {b['id']} references unknown genre {slug}")
    if len({b["id"] for b in books}) != len(books):
        errors.append("duplicate book ids")
    if not 60 <= len(books) <= 150:
        errors.append(f"expected 60-150 books, found {len(books)}")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    out = [
        "-- GENERATED by database/seed/generate_seed_sql.py from database/seed/catalog.json. Do not edit by hand.",
        "-- DEMO CATALOG: public-domain works; descriptions are original summaries written for Bookflix.",
        "-- Idempotent: explicit ids + INSERT IGNORE. No user accounts are seeded.",
        "",
    ]
    out.append("INSERT IGNORE INTO genres (id, name, slug) VALUES")
    out.append(",\n".join(f"  ({g['id']}, {sql_str(g['name'])}, {sql_str(g['slug'])})" for g in genres) + ";")
    out.append("")
    out.append("INSERT IGNORE INTO authors (id, name, bio, created_at) VALUES")
    out.append(",\n".join(
        f"  ({a['id']}, {sql_str(a['name'])}, {sql_str(a.get('bio'))}, UTC_TIMESTAMP(6))" for a in authors) + ";")
    out.append("")
    out.append("INSERT IGNORE INTO books (id, title, description, author_id, isbn, cover_url, published_year, language,"
               " created_at, updated_at) VALUES")
    out.append(",\n".join(
        f"  ({b['id']}, {sql_str(b['title'])}, {sql_str(b['description'])}, {b['authorId']}, NULL, NULL, "
        f"{sql_int(b.get('year'))}, 'en', UTC_TIMESTAMP(6), UTC_TIMESTAMP(6))" for b in books) + ";")
    out.append("")
    pairs = [(b["id"], slug_to_id[s]) for b in books for s in dict.fromkeys(b["genres"])]
    out.append("INSERT IGNORE INTO book_genres (book_id, genre_id) VALUES")
    out.append(",\n".join(f"  ({bid}, {gid})" for bid, gid in pairs) + ";")
    out.append("")

    out.append("-- Populate the denormalised search column for seeded rows (idempotent).")
    out.append("UPDATE books b JOIN authors a ON a.id = b.author_id")
    out.append("   SET b.search_text = CONCAT_WS(' ', b.title, a.name, b.description)")
    out.append(" WHERE b.search_text IS NULL;")
    out.append("")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(genres)} genres, {len(authors)} authors, {len(books)} books)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
